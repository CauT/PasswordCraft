#!/usr/bin/env python3
"""Independent stdlib ZIP producer. Only public synthetic data; never reads vaults."""
import base64
import io
import json
from pathlib import Path
import zipfile

root = Path(__file__).resolve().parents[1]
content = '1PUX synthetic attachment\n中文附件：逐字节保留。\n'.encode()
metadata = {'documentId': 'synthetic-file', 'fileName': '验收.txt', 'decryptedSize': len(content)}
empty = {'documentId': 'synthetic-empty', 'fileName': 'empty.txt', 'decryptedSize': 0}

def item(identifier, title, category, details):
    return {'uuid': identifier, 'createdAt': 100, 'updatedAt': 200, 'categoryUuid': category,
            'state': 'active', 'overview': {'title': title, 'tags': ['synthetic-import']}, 'details': details}

records = [
    item('document', '1PUX document acceptance', '006', {'documentAttributes': metadata}),
    item('login', '1PUX attached login', '001', {'loginFields': [
        {'designation': 'username', 'value': 'synthetic-user'},
        {'designation': 'password', 'value': 'synthetic-password'}], 'sections': [
        {'title': 'Files', 'fields': [{'id': 'file', 'title': 'Attachment', 'value': {'file': metadata}},
                                    {'id': 'text', 'title': 'Preserved field', 'value': {'string': 'kept'}}]}]}),
    item('empty', '1PUX empty document', '006', {'documentAttributes': empty}),
]
export = {'accounts': [{'attrs': {'uuid': 'synthetic-account'}, 'vaults': [
    {'attrs': {'uuid': 'synthetic-vault', 'name': 'Synthetic files'}, 'items': records}]}]}
buffer = io.BytesIO()
with zipfile.ZipFile(buffer, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
    for name, value in [('export.attributes', json.dumps({'version': 3}).encode()),
                        ('export.data', json.dumps(export, ensure_ascii=False).encode()),
                        ('files/', b''), ('files/synthetic-file___验收.txt', content),
                        ('files/synthetic-empty___empty.txt', b'')]:
        info = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = (0o40700 if name.endswith('/') else 0o100600) << 16
        archive.writestr(info, value)
data = buffer.getvalue()
(root / 'Tests/VaultCoreTests/OnePasswordArchiveFixture.swift').write_text(
    '// Generated by scripts/generate-1pux-fixture.py with Python zipfile. Synthetic data only.\n'
    'let onePasswordAttachmentFixture = "' + base64.b64encode(data).decode() + '"\n')
out = root / 'outputs/v0.3-acceptance'
out.mkdir(parents=True, exist_ok=True)
(out / 'synthetic-attachments.1pux').write_bytes(data)
print('Generated independent synthetic 1PUX fixture:', len(data), 'bytes')
