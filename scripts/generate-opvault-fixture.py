#!/usr/bin/env python3
"""Independent OPVault fixture producer: hashlib/HMAC + system OpenSSL AES.
All bytes and the Unicode password are deterministic public synthetic test data.
"""
import base64
import hashlib
import hmac
import json
from pathlib import Path
import struct
import subprocess

root = Path(__file__).resolve().parents[1]
def raw(label, length): return hashlib.shake_256(label.encode()).digest(length)
def b64(data): return base64.b64encode(data).decode()
def js(value): return json.dumps(value, ensure_ascii=False, separators=(',', ':')).encode()
def aes(data, key, iv):
    return subprocess.run(['/usr/bin/openssl', 'enc', '-aes-256-cbc', '-nopad', '-K', key.hex(), '-iv', iv.hex()], input=data, stdout=subprocess.PIPE, check=True).stdout
def mac(data, keys): return hmac.new(keys[32:], data, hashlib.sha256).digest()
def op(data, keys, label):
    iv = raw(label + '-iv', 16)
    padded = raw(label + '-pad', 16 - len(data) % 16) + data
    sealed = b'opdata01' + struct.pack('<Q', len(data)) + iv + aes(padded, keys[:32], iv)
    return sealed + mac(sealed, keys)
def wrap(prefix, value, suffix): return prefix.encode() + js(value) + suffix.encode()
password = '合成-OPVault-密码!'
salt = raw('salt', 16)
derived = hashlib.pbkdf2_hmac('sha512', password.encode(), salt, 1000, 64)
master_seed, overview_seed = raw('master', 256), raw('overview', 64)
master, overview = hashlib.sha512(master_seed).digest(), hashlib.sha512(overview_seed).digest()
profile_id, folder_id = '1' * 32, 'F' * 32
profile = {'uuid': profile_id, 'profileName': 'Synthetic', 'iterations': 1000, 'salt': b64(salt), 'masterKey': b64(op(master_seed, derived, 'master')), 'overviewKey': b64(op(overview_seed, derived, 'overview')), 'createdAt': 100, 'updatedAt': 200}
files = {'default/profile.js': wrap('var profile=', profile, ';')}
folder = {'uuid': folder_id, 'created': 100, 'updated': 200, 'smart': True, 'overview': b64(op(js({'title': '合成文件夹', 'predicate': 'synthetic rule preserved, never executed'}), overview, 'folder'))}
files['default/folders.js'] = wrap('loadFolders(', {folder_id: folder}, ');')

def sign(record):
    def value(v): return ('1' if v else '0') if isinstance(v, bool) else str(v)
    message = ''.join(k + value(record[k]) for k in sorted(record) if k not in ('hmac', 'folder')).encode()
    record['hmac'] = b64(mac(message, overview))
    return record

keys = {}
for letter, title, trashed in [('A', 'Synthetic OPVault Login', False), ('B', 'Synthetic OPVault Trash', True)]:
    identity = letter * 32; key = raw('item-' + letter, 64); keys[identity] = key
    key_iv = raw('item-iv-' + letter, 16); sealed_key = key_iv + aes(key, master[:32], key_iv)
    details = {'fields': [{'designation': 'username', 'value': 'synthetic-user'}, {'designation': 'password', 'value': 'synthetic-secret'}], 'notesPlain': '本地迁移测试', 'sections': [{'name': 'extra', 'title': 'Extra', 'fields': [{'n': 'TOTP_fixture', 't': 'OTP', 'k': 'concealed', 'v': 'JBSWY3DPEHPK3PXP'}, {'n': 'complex', 't': 'Preserved', 'k': 'address', 'v': {'city': '上海'}}]}], 'passwordHistory': [{'value': 'synthetic-old', 'time': 150}]}
    ov = {'title': title, 'url': 'https://example.invalid', 'URLs': [{'u': 'https://second.invalid'}], 'tags': ['synthetic']}
    record = {'uuid': identity, 'category': '001', 'created': 100, 'updated': 200, 'tx': 200, 'folder': folder_id, 'trashed': trashed, 'fave': 0, 'k': b64(sealed_key + mac(sealed_key, master)), 'o': b64(op(js(ov), overview, 'o-' + letter)), 'd': b64(op(js(details), key, 'd-' + letter))}
    files['default/band_' + letter + '.js'] = wrap('ld(', {identity: sign(record)}, ');')
identity = 'C' * 32
files['default/band_C.js'] = wrap('ld(', {identity: sign({'uuid': identity, 'category': '099', 'created': 100, 'updated': 200, 'tx': 200})}, ');')
for letter, name, payload, version, trashed in [('D', '中文.txt', '独立 OPVault 附件\n'.encode(), 1, False), ('E', 'empty.txt', b'', 2, False), ('9', 'removed.txt', b'removed attachment preserved', 1, True)]:
    owner = 'A' * 32; identity = letter * 32; key = keys[owner]
    ov = {'filename': name}
    metadata = {'uuid': identity, 'itemUUID': owner, 'createdAt': 100, 'updatedAt': 200, 'overview': b64(op(js(ov), overview, 'attach-o-' + letter)), 'trashed': trashed, 'contentsSize': len(payload)}
    icon = op(b'synthetic icon', key, 'icon-' + letter)
