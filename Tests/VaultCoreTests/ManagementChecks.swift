import Foundation
import VaultCore

func runManagementChecks() throws {
    let first = VaultItem(title:"a",password:"password123")
    let second = VaultItem(title:"b",password:"password123",state:.archived)
    let discarded = VaultItem(title:"deleted",password:"password123",state:.trashed,deletedAt:Date())
    let strong = VaultItem(title:"generated",password:"L6#wr3_X8?cZ2!bH9")
    let repeated = VaultItem(title:"pattern",password:"xyxyxyxyxyxy")
    let findings = PasswordHealth.inspect([first,second,discarded,strong,repeated])
    XCTAssertEqual(Set(findings.map(\.itemID)),Set([first.id,second.id,repeated.id]))
    let risk = try XCTUnwrap(findings.first { $0.itemID == first.id })
    XCTAssertEqual(risk.reuseCount,2); XCTAssertTrue(risk.reasons.contains(.short)); XCTAssertTrue(risk.reasons.contains(.common)); XCTAssertTrue(risk.reasons.contains(.reused))
    let longReuse = VaultItem(title:"copied",password:strong.password)
    XCTAssertEqual(PasswordHealth.inspect([strong,longReuse]).count,2)
    XCTAssertEqual(PasswordHealth.inspect([VaultItem(title:"empty")]).count,0)

    let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
    try FileManager.default.createDirectory(at:root,withIntermediateDirectories:true)
    defer { try? FileManager.default.removeItem(at:root) }
    let file = root.appendingPathComponent("batch.localvault")
    let session = try VaultSession.create(at:file,password:"Synthetic-batch-master!",backupRoot:root.appendingPathComponent("backups"))
    try session.save(items:[first,second,strong])
    let selection = Set([first.id,second.id]); let date = Date(timeIntervalSince1970:1_800_000_000)
    let next = try BatchEdit.applying(.addTag(" 检查 "),to:session.items,ids:selection,at:date)
    try session.save(items:next)
    XCTAssertEqual(session.items.filter { $0.tags == ["检查"] }.count,2)
    XCTAssertEqual(session.items.first { $0.id == strong.id },strong)
    XCTAssertEqual(session.allRevisions.count,2)
    try session.save(items:BatchEdit.applying(.addTag("检查"),to:session.items,ids:selection))
    XCTAssertEqual(session.allRevisions.count,2)
    try session.save(items:BatchEdit.applying(.trash,to:session.items,ids:selection,at:date))
    XCTAssertEqual(session.items.filter { $0.state == .trashed && $0.deletedAt == date }.count,2)
    XCTAssertEqual(session.allRevisions.count,4)
    XCTAssertThrowsError(try BatchEdit.applying(.archive,to:session.items,ids:selection))
    XCTAssertThrowsError(try BatchEdit.applying(.favorite(true),to:session.items,ids:[UUID()]))
    XCTAssertThrowsError(try BatchEdit.applying(.addTag(" "),to:session.items,ids:[strong.id]))
    try session.save(items:BatchEdit.applying(.restore,to:session.items,ids:selection,at:date))
    XCTAssertTrue(session.items.allSatisfy { $0.state == .active && $0.deletedAt == nil })
    let stale = try VaultSession.open(at:file,password:"Synthetic-batch-master!",backupRoot:root.appendingPathComponent("backups"))
    let staged = try BatchEdit.applying(.favorite(true),to:stale.items,ids:selection)
    try session.save(items:BatchEdit.applying(.archive,to:session.items,ids:selection))
    XCTAssertThrowsError(try stale.save(items:staged))
    XCTAssertFalse(stale.items.contains { $0.favorite })
    let reopened = try VaultSession.open(at:file,password:"Synthetic-batch-master!",backupRoot:root.appendingPathComponent("backups"))
    XCTAssertEqual(reopened.items.filter { $0.state == .archived }.count,2)
    XCTAssertFalse(reopened.items.contains { $0.favorite })
    print("PASS offline password warnings and atomic batch history, no-op, trash/restore and stale-session failure")
}
